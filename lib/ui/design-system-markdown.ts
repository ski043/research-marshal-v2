import {
  type ColorToken,
  type DesignSystem,
  formatPx,
  formatRatio,
  passes,
  THEME_NAMES,
  type TypeStep,
  type Utility,
} from "./design-system";

export const TOKENS_FILE = ".claude/skills/design-system/references/tokens.md";
export const TOKENS_COMMAND = "pnpm design:tokens";

const code = (text: string) => `\`${text}\``;
const cell = (text: string) => text.replace(/\|/g, "\\|");

function table(head: readonly string[], rows: readonly string[][]): string {
  return [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ].join("\n");
}

const value = (token: ColorToken, theme: "light" | "dark") =>
  `${code(token.value[theme].css)} ${code(token.value[theme].hex)}`;

function sizeOf(step: TypeStep): string {
  return step.sizes
    .map(
      (size) =>
        `${formatPx(size.px)} (${size.rem}rem)${size.from === null ? "" : ` from ${size.from}px`}`,
    )
    .join(", ");
}

function lineHeightOf(step: TypeStep): string {
  return step.sizes
    .map((size) =>
      size.lineHeightPx === null ? "inherited" : formatPx(size.lineHeightPx),
    )
    .join(", ");
}

const utilityTable = (rows: readonly Utility[]) =>
  table(
    ["Class", "Value", "Use"],
    rows.map((row) => [code(row.className), row.value ?? "", row.use]),
  );

/** `references/tokens.md` of the design-system skill: the model as tables. */
export function tokensMarkdown(system: DesignSystem): string {
  const out: string[] = [
    `Generated by ${code(TOKENS_COMMAND)} from ${code("app/globals.css")} and ${code("lib/ui/design-system.ts")}. Do not edit this file: change the source, then run the command.`,
    "",
    "# Design tokens",
    "",
    `Every colour is written as ${code("oklch()")} in ${code("app/globals.css")}, once for ${code(":root")} (light) and once for ${code(".dark")}. The hex value is the same colour in sRGB. A Tailwind utility takes the token name without the dashes: ${code("--primary-ink")} is ${code("text-primary-ink")}, ${code("bg-primary-ink")}, ${code("border-primary-ink")}.`,
    "",
    "## Colour",
  ];

  for (const group of system.groups) {
    out.push(
      "",
      `### ${group.title}`,
      "",
      group.rule,
      "",
      table(
        ["Token", "Role", "Light", "Dark", "Use"],
        group.tokens.map((token) => [
          code(token.token),
          token.name,
          value(token, "light"),
          value(token, "dark"),
          token.use,
        ]),
      ),
    );
  }

  out.push(
    "",
    "## Contrast",
    "",
    "Measured with WCAG 2.2 from the values above. Text must reach 4.5:1 and a shape that carries meaning without text 3:1. A pair that is not in this table is not checked: add it to the role before you rely on it.",
    "",
    table(
      ["Colour", "On", "Kind", "Floor", ...THEME_NAMES.map((t) => `In ${t}`)],
      system.colors.flatMap((token) =>
        token.checks.map((check) => [
          code(token.token),
          code(check.on),
          check.kind,
          `${check.floor}:1`,
          ...THEME_NAMES.map(
            (theme) =>
              `${formatRatio(check.ratio[theme])} ${passes(check, theme) ? "pass" : "FAIL"}`,
          ),
        ]),
      ),
    ),
    "",
    "## Typography",
    "",
    table(
      ["Family", "Class", "Use"],
      system.fonts.map((font) => [font.name, code(font.className), font.use]),
    ),
    "",
    "The scale, by the job of each step. Write the classes as they stand here.",
    "",
    table(
      ["Step", "Classes", "Size", "Line height", "Weight", "Family", "Where"],
      system.type.map((step) => [
        step.job,
        code(step.className),
        sizeOf(step),
        lineHeightOf(step),
        String(step.weight),
        step.family,
        step.where,
      ]),
    ),
    "",
    "## Shape and depth",
    "",
    `The base radius ${code("--radius")} is ${system.settings.find((s) => s.token === "--radius")?.value.light}. Each step is a multiple of it.`,
    "",
    table(
      ["Class", "Size", "Use"],
      [
        ...system.radii.map((radius) => [
          code(radius.className),
          `${formatPx(radius.px)} (${Number(radius.rem.toFixed(4))}rem)`,
          radius.use ?? "Not used. Do not start to use it.",
        ]),
        [code(system.fullRadius.className), "round", system.fullRadius.use],
      ],
    ),
    "",
    "Shadows are the ones of Tailwind's default theme.",
    "",
    utilityTable(system.shadows),
    "",
    "Spacing is a multiple of 4px.",
    "",
    utilityTable(system.spacing),
    "",
    "## Motion",
    "",
    utilityTable(system.durations),
    "",
    utilityTable(system.easings),
    "",
    `The one long loop is the placeholder of the prompt box: ${code(system.placeholderAnimation)}.`,
    "",
    "## Other tokens",
    "",
    table(
      ["Token", "Role", "Light", "Dark", "Use"],
      system.settings.map((setting) => [
        code(setting.token),
        setting.name,
        code(setting.value.light),
        code(setting.value.dark),
        setting.use,
      ]),
    ),
    "",
  );
  return out.join("\n");
}
